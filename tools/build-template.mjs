#!/usr/bin/env node
/**
 * build-template.mjs - inline aws/lambda.cjs into aws/template.yaml.
 *
 * The deployable template is one self-contained file, so it can be uploaded
 * in the AWS console with no CLI, no bucket and no packaging step. The Lambda
 * source stays a normal, tested file; this script is the only bridge, and
 * aws/template.test.js fails if the committed template ever drifts from it.
 *
 * CloudFormation caps inline ZipFile code at 4096 characters, so comment-only
 * lines and blank lines are stripped here. Behaviour is unchanged: comments in
 * lambda.cjs are always on their own lines for exactly this reason.
 *
 *   node tools/build-template.mjs          writes aws/template.yaml
 *   node tools/build-template.mjs --check  exits 1 if it is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../aws/', import.meta.url);
export const ZIPFILE_LIMIT = 4096;

export function inlineCode() {
  return readFileSync(new URL('lambda.cjs', root), 'utf8')
    .split('\n')
    .filter(l => l.trim() && !l.trim().startsWith('//'))
    .join('\n');
}

export function buildTemplate() {
  const code = inlineCode();
  if (code.length > ZIPFILE_LIMIT) throw new Error(`inline Lambda is ${code.length} chars, over the ${ZIPFILE_LIMIT} limit`);
  const src = readFileSync(new URL('template.src.yaml', root), 'utf8');
  const indented = code.split('\n').map(l => `          ${l}`).join('\n');
  return '# GENERATED by tools/build-template.mjs from aws/template.src.yaml and\n' +
    '# aws/lambda.cjs. Do not edit by hand: edit those and re-run the script.\n' +
    src.replace('__LAMBDA_CODE__', indented);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = buildTemplate();
  const target = new URL('template.yaml', root);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch {}
    if (current !== out) { console.error('aws/template.yaml is out of date: run npm run build-template'); process.exit(1); }
    console.log('aws/template.yaml is up to date');
  } else {
    writeFileSync(target, out);
    console.log(`wrote aws/template.yaml (inline Lambda ${inlineCode().length}/${ZIPFILE_LIMIT} chars)`);
  }
}
